export const DICTIONARIES: Record<Lang, Dict> = { da, en };

/** A function that looks up `key` and fills in {vars}. A missing key shows
 *  itself, so it is easy to spot (and the tests catch it). */
export function translator(lang: Lang) {
  const dict = DICTIONARIES[lang];
  return (key: string, vars: Record<string, string | number> = {}) =>
    (dict[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}

const LANG_KEY = "kds-lang";

export function savedLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY);
    return v === "en" ? "en" : "da";
  } catch {
    return "da";
  }
}

export function saveLang(lang: Lang): void {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    // Not remembered in private mode.
  }
}
